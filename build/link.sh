#!/bin/sh
# Links VLC's static archives, our webaudio module and the bridge into
# libvlc.js + libvlc.wasm. Runs inside the build container (./build.sh link).
set -eu

. /opt/emsdk/emsdk_env.sh >/dev/null 2>&1

S=/cache/vlc
B=$S/build-emscripten
C=$S/contrib/wasm32-unknown-emscripten
N=/work/native
OUT=/work/packages/core/wasm
OBJ=/cache/link
PROFILE=${PROFILE:-release}
mkdir -p "$OBJ" "$OUT"

case "$PROFILE" in
  release) OPT="-O3"; LINK_OPT="-O3 --profiling-funcs -sASSERTIONS=0" ;;
  debug)   OPT="-O1 -g"; LINK_OPT="-O1 -g -sASSERTIONS=2" ;;
  *) echo "PROFILE must be release or debug" >&2; exit 2 ;;
esac

# Modules left out of the binary. The GL ones need a WebGL context on a VLC
# thread, which we do not give them (frames go to the page through vmem);
# the rest are test fixtures or pull in large libraries for demos.
EXCLUDE='gles2 egl_display_generic glinterop_sw glsampler_builtin glfilter_draw
glfilter_mock gladjust glblend opengl_filter placebo placebo_gles2 pl_scale vgl
opencv_example opencv_wrapper demux_mock hxxxhelper_testdec blendbench fingerprinter sam3
emscripten_inhibit'
# emscripten_inhibit calls navigator.wakeLock on the runtime thread, which here
# is a Worker without one; the page-side Player takes the wake lock instead.

echo "==> compiling native/"
CFLAGS="$OPT -pthread -msimd128 -fwasm-exceptions -sSUPPORT_LONGJMP=wasm -std=gnu17 -Wall -Wno-unused-parameter"
emcc $CFLAGS -DHAVE_CONFIG_H -I"$B" -I"$S/include" \
  -DMODULE_NAME=webaudio -DMODULE_STRING='"webaudio"' \
  -c "$N/webaudio.c" -o "$OBJ/webaudio.o"
emcc $CFLAGS -DHAVE_CONFIG_H -I"$B" -I"$S/include" \
  -DMODULE_NAME=webcodecs -DMODULE_STRING='"webcodecs"' \
  -c "$N/webcodecs.c" -o "$OBJ/webcodecs.o"
emcc $CFLAGS -DHAVE_CONFIG_H -I"$B" -I"$S/include" \
  -DMODULE_NAME=webframe -DMODULE_STRING='"webframe"' \
  -c "$N/webframe.c" -o "$OBJ/webframe.o"
# sout (transcoding, remuxing, recording) is present when VLC was configured with it.
HAS_SOUT=$(grep -q '^#define ENABLE_SOUT 1' "$B/config.h" && echo 1 || echo 0)
emcc $CFLAGS -DWV_HAS_SOUT=$HAS_SOUT -DHAVE_CONFIG_H -I"$B" -I"$S/include" -c "$N/bridge.c" -o "$OBJ/bridge.o"
emcc $CFLAGS -c "$N/compat.c" -o "$OBJ/compat.o"

echo "==> generating the static module table"
PLUGINS=""
PROTOS=""
LIST=""
for a in "$B"/modules/.libs/lib*_plugin.a; do
  name=$(basename "$a" | sed 's/^lib//; s/_plugin\.a$//')
  case " $(echo $EXCLUDE) " in *" $name "*) continue ;; esac
  entry=$(emnm -g "$a" 2>/dev/null | awk '$2=="T" && $3 ~ /^vlc_entry__/ && $3 !~ /^vlc_entry__(api_version|copyright|license)/ {print $3; exit}')
  [ -n "$entry" ] || { echo "  no entry in $name, skipped"; continue; }
  PLUGINS="$PLUGINS $a"
  PROTOS="${PROTOS}VLC_ENTRY_FUNC($entry);\n"
  LIST="${LIST}    $entry,\n"
done
for ours in webaudio webcodecs webframe; do
  PROTOS="${PROTOS}VLC_ENTRY_FUNC(vlc_entry__$ours);\n"
  LIST="${LIST}    vlc_entry__$ours,\n"
done
printf '// Generated by build/link.sh\n#include <stddef.h>\n#include <vlc_plugin.h>\n%b\nconst vlc_plugin_cb vlc_static_modules[] = {\n%b    NULL\n};\n' \
  "$PROTOS" "$LIST" > "$OBJ/vlc-modules.c"
emcc $CFLAGS -I"$S/include" -I"$B" -c "$OBJ/vlc-modules.c" -o "$OBJ/vlc-modules.o"
echo "  $(grep -c 'VLC_ENTRY_FUNC(' "$OBJ/vlc-modules.c") modules"

# Helper archives the plugins share (avcodec_common, vlc_http, ...).
HELPERS=$(find "$B/modules" -path '*/.libs/*' -name '*.a' ! -name '*_plugin.a')
CONTRIB=$(ls "$C"/lib/*.a | grep -v -e opencv -e glslang -e SPIRV -e HLSL -e OGLCompiler \
  -e OSDependent -e MachineIndependent -e GenericCodeGen -e ggml -e placebo)

echo "==> linking"
emcc $LINK_OPT -pthread -msimd128 -fwasm-exceptions -sSUPPORT_LONGJMP=wasm \
  "$OBJ/bridge.o" "$OBJ/compat.o" "$OBJ/webaudio.o" "$OBJ/webcodecs.o" "$OBJ/webframe.o" "$OBJ/vlc-modules.o" \
  -Wl,--start-group $PLUGINS $HELPERS \
  "$B/lib/.libs/libvlc.a" "$B/src/.libs/libvlccore.a" "$B/compat/.libs/libcompat.a" \
  $CONTRIB -Wl,--end-group \
  -lm -lstdc++ \
  -sMODULARIZE=1 -sEXPORT_ES6=1 -sEXPORT_NAME=createLibVLCModule \
  -sENVIRONMENT=worker,node \
  -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=128MB -sMAXIMUM_MEMORY=4GB \
  -sSTACK_SIZE=1MB -sDEFAULT_PTHREAD_STACK_SIZE=1MB \
  -sPTHREAD_POOL_SIZE='Module["pthreadPoolSize"]||12' -sPTHREAD_POOL_SIZE_STRICT=0 \
  -sFORCE_FILESYSTEM=1 -lworkerfs.js -lnodefs.js \
  -sEXPORTED_FUNCTIONS=_malloc,_free,_wv_submit,_wv_api_names,_wv_call_layout,_wv_wc_opened,_wv_wc_push,_wv_wc_drained,_wv_wc_error,_wv_wc_free \
  -sEXPORTED_RUNTIME_METHODS=FS,WORKERFS,NODEFS,UTF8ToString,stringToNewUTF8,HEAPU8,HEAP32,HEAPF64,wasmMemory \
  -o "$OUT/libvlc.js"

# Exceptions: everything was compiled with the legacy wasm EH encoding
# (try/catch). Firefox warns that it is deprecated, and linking with
# -sWASM_LEGACY_EXCEPTIONS=0 only converts what emcc compiles at link time,
# leaving a module that mixes try and try_table, which Safari rejects outright.
# Translate the finished module as a whole instead.
echo "==> translating exception handling to exnref (try_table)"
# The feature flags must be explicit: with --detect-features the pass finds no
# EH feature in the (stripped) target_features section and silently does nothing.
# -g keeps the function names that --profiling-funcs put there.
wasm-opt "$OUT/libvlc.wasm" -g --translate-to-exnref \
  --enable-threads --enable-bulk-memory --enable-bulk-memory-opt --enable-exception-handling \
  --enable-simd --enable-nontrapping-float-to-int --enable-sign-ext --enable-mutable-globals \
  --enable-reference-types --enable-multivalue \
  -o "$OUT/libvlc.wasm.tmp" && mv "$OUT/libvlc.wasm.tmp" "$OUT/libvlc.wasm"

cp "$OBJ/vlc-modules.c" "$OUT/modules.generated.c"
ls -la "$OUT"
